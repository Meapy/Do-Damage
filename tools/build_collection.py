"""Builds the Collection's list (the Collector in the vault: CollectionHandler.cs on the server, the
Rust client's collection.rs) from the game's data, as the wiki reads it (tools/build_wiki.py):

    python tools/build_collection.py [--check]

Writes source/Shared/resources/data/collection.json:

- `all`: every piece of gear a player can get (weapons, abilities, armor and rings that drop, are
  forged, sold or handed out), in the order the client lists them: by slot type, then tier, then
  name. The Collection's "All" view.
- `groups`: where the untiered gear comes from, for its "Dungeons" view: each dungeon (hardest
  first, by the wiki's difficulty) with the untiered gear its monsters and bosses drop, the
  Empowered Elder bosses' unique items, the realm's own, then what the Divine Forge makes. An item
  from two places is in both.

Run it after adding gear, drops or dungeons; `--check` fails when the file is out of date (as a
test would).
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_wiki as bw  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "source", "Shared", "resources", "data", "collection.json")

# kinds of gear that are no reward of play (the wiki's gear groups)
NOT_COLLECTED = {"admin", "reward", "unobtainable", "test"}


def build():
    g = bw.Gen()
    d = g.d
    gear = [it for it in d.gear() if it["group"] not in NOT_COLLECTED]
    forged = {r["result"] for r in g.forge}
    starters = set()
    for slot in {it["slot"] for it in gear}:
        st = d.gear_items(slot)
        if st:
            starters.add(st["id"])

    def obtainable(it):
        oid = it["id"]
        return bool(it["tier_loot"] or any(c for _, c in g.idx.get(oid, [])) or oid in forged
                    or oid in g.bazaar or oid in starters)

    gear = [it for it in gear if obtainable(it)]
    ids = {it["id"] for it in gear}
    untiered = {it["id"] for it in gear if it["tier"] < 0}
    gear.sort(key=lambda it: (it["slot"], it["tier"] if it["tier"] >= 0 else 99, it["name"].lower()))

    def ut_drops(monsters):
        out = []
        for m in monsters:
            for kind, oid, chance in d.drops(m):
                if kind == "item" and oid in untiered and oid not in out:
                    out.append(oid)
        return out

    groups = []
    in_dungeons = set()
    for x in g.dungeons():
        w = d.worlds.get(x["id"])
        if not w:
            continue
        monsters = list(dict.fromkeys(d.map_objects(w) + g.bosses_of(x["id"]) + ([x["boss"]] if x["boss"] else [])))
        in_dungeons.update(monsters)
        items = ut_drops(monsters)
        if not items:
            continue
        portal = next(iter(g.portals.get(x["id"], [])), None)
        groups.append({"name": x["name"], "icon": portal, "level": x["level"], "items": items})
    groups.sort(key=lambda gr: (-(gr["level"] or 0), gr["name"].lower()))
    necromantic = sorted(
        {b["item"] for b in d.resurrection()["bosses"] if b["item"] in untiered},
        key=lambda o: (d.name(o).lower(), o),
    )
    if necromantic:
        groups.append({
            "name": "Drops from Necromantic Boss",
            "icon": "Necromantic Relic",
            "level": 0,
            "items": necromantic,
        })
    # the realm's: dropped by monsters no dungeon holds (its gods, events and their minions)
    realm = []
    for oid in sorted(untiered, key=lambda o: (d.name(o).lower(), o)):
        if any(c and m not in in_dungeons and not bw.HIDDEN_MONSTER.search(m) for m, c in g.idx.get(oid, [])):
            realm.append(oid)
    if realm:
        groups.append({"name": "Realm", "icon": "Realm Portal", "level": 0, "items": realm})
    forge = sorted({oid for oid in forged if oid in untiered}, key=lambda o: (d.name(o).lower(), o))
    if forge:
        groups.append({"name": "Divine Forge", "icon": "Divine Forge", "level": 0, "items": forge})
    for gr in groups:
        gr["items"] = [i for i in gr["items"] if i in ids]
    return {
        "_comment": "Generated by tools/build_collection.py from the game's data, as the wiki reads it. Do not edit.",
        "all": [it["id"] for it in gear],
        "groups": [gr for gr in groups if gr["items"]],
    }


def dump(data):
    lines = ["{", '  "_comment": %s,' % json.dumps(data["_comment"]), '  "all": [']
    lines += ["    %s%s" % (json.dumps(i), "," if k < len(data["all"]) - 1 else "") for k, i in enumerate(data["all"])]
    lines += ["  ],", '  "groups": [']
    for k, gr in enumerate(data["groups"]):
        lines.append('    {"name": %s, "icon": %s, "level": %d, "items": %s}%s' % (
            json.dumps(gr["name"]), json.dumps(gr["icon"]), gr["level"] or 0, json.dumps(gr["items"]),
            "," if k < len(data["groups"]) - 1 else ""))
    lines += ["  ]", "}", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = ap.parse_args()
    text = dump(build())
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if args.check:
        if old.replace("\r\n", "\n") != text:
            sys.exit("collection.json is out of date: run python tools/build_collection.py")
        print("collection.json is up to date")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    data = json.loads(text)
    print("collection.json: %d items, %d groups" % (len(data["all"]), len(data["groups"])))


if __name__ == "__main__":
    main()
