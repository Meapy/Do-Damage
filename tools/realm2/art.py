"""The art of Realm 2 (tools/build_realm2.py draws it): a palette for each area and its monsters,
quest monsters and scenery as pixel maps, one character a pixel ('.' is clear).

Palette letters, the same in every area:
  1 2 3   the area's main colour, dark to light
  4 5 6   its second colour, dark to light
  7 8     its glow (eyes, magic), dark and light
  w k     white and near black
  e E     an eye or a wound, dark and light
  g G     grey, dark and light
  b B     brown (wood, bone shadow), dark and light
  y       a warm highlight (gold, flame)

Each monster has a standing frame and may have an attack frame; the walk frames are made from the
standing frame by build_realm2.py. Pictures face right. The client draws the black outline.
"""


def hexc(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


COMMON = {"w": "#f4f4f0", "k": "#141018", "g": "#5a5a66", "G": "#a4a4b0", "b": "#5e3e24", "B": "#9a6c40",
          "y": "#ffd24a", "e": "#b01830", "E": "#ff5a6a"}


def palette(**colours):
    p = dict(COMMON)
    for k, v in colours.items():
        p[k.lstrip("_")] = v
    return {k: hexc(v) for k, v in p.items()}


