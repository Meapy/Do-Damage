"""The Ice Tomb's creatures and shots, placed pixel by pixel (tools/ice_tomb/art.py uses them).

Drawn as the game's own monsters are: a bold silhouette, two or three tones to a material lit from
the upper left, solid pixels only (the client draws the black outline and the shadow), eyes and
cores that glow, facing right. Each sprite is a grid of letters, one to a pixel ('.' is empty),
over a palette; a frame is the grid with some rows swapped (walking, attacking)."""
from PIL import Image

# the tomb's colours, one letter each (a sprite may give its own on top)
BASE = {
    "k": "#0b1226",   # the dark
    "n": "#1c3466",   # navy
    "b": "#2f6fd0",   # deep ice
    "i": "#5fb4f5",   # ice
    "l": "#aee6ff",   # pale ice
    "w": "#ffffff",
    "c": "#3ef0ff",   # glow
    "g": "#4c5872",   # stone, dark
    "G": "#8494b0",   # stone
    "h": "#d6e2f0",   # bone, snow, wrappings
    "H": "#f4f8fc",
    "p": "#5a24b0",   # violet
    "P": "#a878ff",
    "q": "#e0ccff",
    "a": "#14946a",   # aurora
    "A": "#46f0a6",
    "r": "#a8141e",   # blood
    "R": "#ff4248",
    "y": "#c88a1c",   # gold
    "Y": "#ffd860",
    "o": "#5a3a20",   # wood
    "O": "#8c6238",
}


def _rgba(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def paint(rows, palette=None, size=None):
    pal = dict(BASE)
    pal.update(palette or {})
    h = size or len(rows)
    w = size or max(len(r) for r in rows)
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        assert len(row) <= w, ("row too wide", y, row)
        for x, ch in enumerate(row):
            if ch != ".":
                img.putpixel((x, y), _rgba(pal[ch]))
    return img


def grid(text, size):
    rows = [r.rstrip() for r in text.strip("\n").split("\n")]
    assert len(rows) <= size, (len(rows), text[:40])
    rows = [r.ljust(size, ".") for r in rows] + ["." * size] * (size - len(rows))
    for r in rows:
        assert len(r) == size, ("row is %d wide, not %d: %r" % (len(r), size, r))
    return rows


def frame(base, changes):
    """the grid with some rows replaced: {row: text}"""
    rows = list(base)
    for y, text in changes.items():
        rows[y] = text.ljust(len(base[0]), ".")
        assert len(rows[y]) == len(base[0]), (y, text)
    return rows


class Sprite:
    def __init__(self, size, base, walk=None, attack=None, palette=None):
        self.size = size
        self.base = grid(base, size)
        self.walk = frame(self.base, walk or {})
        self.attack = frame(self.base, attack or {})
        self.palette = palette or {}

    def frames(self, palette=None):
        """([stand, walk], attack)"""
        pal = dict(self.palette)
        pal.update(palette or {})
        return [paint(self.base, pal, self.size), paint(self.walk, pal, self.size)], paint(self.attack, pal, self.size)


