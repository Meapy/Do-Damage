using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using NLog;
using WorldServer.core.net.datas;
using WorldServer.core.objects;
using WorldServer.core.structures;
using WorldServer.core.worlds;
using WorldServer.logic;
using WorldServer.logic.loot;
using WorldServer.networking.packets.outgoing;

namespace WorldServer.core.resurrection
{
    /// <summary>One boss that can be raised: its remains, its Empowered form and how the souls name it.</summary>
    public sealed class BossInfo
    {
        public string Boss, Name, Dungeon;
        public ushort BossType, RemainsType, EmpoweredType;
        public int SoulDamage;
    }

    /// <summary>
    /// The boss resurrection. An Elder dungeon's boss leaves its remains when it dies
    /// (<see cref="BossRemains"/>), circled by escaping souls that call out whoever nearby carries a
    /// Necromantic Relic. The relic, used within 3 tiles of the remains, raises the boss again in its
    /// Empowered form (<see cref="Empowered"/>): the Elder boss's own behaviour, sped up, with more
    /// health and harder shots, the souls' attacks on top, and its loot rolled again at better chances.
    /// The bosses, their remains and forms, and the loot are generated by tools/build_resurrection.py
    /// (resources/data/resurrection.json and xml/custom/Resurrection.xml).
    /// </summary>
    public static class BossResurrection
    {
        private static readonly Logger Log = LogManager.GetCurrentClassLogger();

        private static readonly Dictionary<ushort, BossInfo> ByBoss = new Dictionary<ushort, BossInfo>();
        public static string RelicId { get; private set; } = "Necromantic Relic";
        public static int RemainsMs { get; private set; } = 75000;
        public static ushort RitualSoulType { get; private set; }
        public static ushort WailingSoulType { get; private set; }
        public static int SoulBolt { get; private set; } = 90;
        private static double _relicChance = 0.05;
        private static double _relicThreshold = 0.02;

        // Reads the bosses and gives each Empowered form its Elder boss's behaviour, with the
        // Elder boss's loot and the better rolls on top. Run once the behaviours are built.
        internal static void Initialize(BehaviorDb db)
        {
            ByBoss.Clear();
            var server = db.GameServer;
            var data = server.Resources.GameData;
            var path = Path.Combine(server.Resources.ResourcePath, "data", "resurrection.json");
            if (!File.Exists(path))
            {
                Log.Warn($"No {path}: bosses leave no remains.");
                return;
            }

            using var doc = JsonDocument.Parse(File.ReadAllText(path));
            var root = doc.RootElement;
            RelicId = root.GetProperty("relic").GetString();
            _relicChance = root.GetProperty("relicChance").GetDouble();
            _relicThreshold = root.GetProperty("relicThreshold").GetDouble();
            RemainsMs = root.GetProperty("corpseSeconds").GetInt32() * 1000;
            SoulBolt = root.GetProperty("soulBolt").GetInt32();
            RitualSoulType = data.IdToObjectType.TryGetValue(root.GetProperty("ritualSoul").GetString(), out var rs) ? rs : (ushort)0;
            WailingSoulType = data.IdToObjectType.TryGetValue(root.GetProperty("wailingSoul").GetString(), out var ws) ? ws : (ushort)0;

            foreach (var b in root.GetProperty("bosses").EnumerateArray())
            {
                var info = new BossInfo
                {
                    Boss = b.GetProperty("boss").GetString(),
                    Name = b.GetProperty("name").GetString(),
                    Dungeon = b.GetProperty("dungeon").GetString(),
                    SoulDamage = b.GetProperty("soulDamage").GetInt32(),
                };
                if (!data.IdToObjectType.TryGetValue(info.Boss, out info.BossType)
                    || !data.IdToObjectType.TryGetValue(b.GetProperty("corpse").GetString(), out info.RemainsType)
                    || !data.IdToObjectType.TryGetValue(b.GetProperty("empowered").GetString(), out info.EmpoweredType))
                {
                    Log.Warn($"Resurrection: no object data for {info.Boss} or its remains or Empowered form.");
                    continue;
                }
                if (!db.Definitions.TryGetValue(info.BossType, out var def))
                {
                    Log.Warn($"Resurrection: {info.Boss} has no behaviour; it leaves no remains.");
                    continue;
                }

                // its own loot, or the loot of the balloon a chest spawner left for it (the
                // Shatters' bosses carry none themselves, and the spawner is gone by now)
                var own = def.Item2;
                if (b.TryGetProperty("lootFrom", out var from) && data.IdToObjectType.TryGetValue(from.GetString(), out var fromType)
                    && db.Definitions.TryGetValue(fromType, out var fromDef))
                    own = fromDef.Item2;
                var drops = new List<MobDrops>();
                if (own != null)
                    drops.AddRange(own);
                foreach (var l in b.GetProperty("loot").EnumerateArray())
                    drops.Add(new ItemLoot(l[0].GetString(), l[1].GetDouble(), 0, 0.01));
                db.Definitions[info.EmpoweredType] = new Tuple<State, Loot>(def.Item1, new Loot(drops.ToArray()));
                ByBoss[info.BossType] = info;
            }
            Log.Info($"Resurrection: {ByBoss.Count} bosses leave remains.");
        }

        public static bool Leaves(Enemy enemy) => ByBoss.ContainsKey(enemy.ObjectType);

        // Loot.ExtraLootTables: the relic, from every boss that leaves remains
        public static void AddRelicDrop(Enemy enemy, List<LootDef> list)
        {
            if (Leaves(enemy))
                list.Add(new LootDef(RelicId, _relicChance, _relicThreshold));
        }

        // Enemy.Death: a boss that can be raised leaves its remains; an Empowered one lets its souls go
        public static void BossDied(Enemy enemy)
        {
            var world = enemy.World;
            if (world == null || enemy.SpawnedByBehavior)
                return;

            if (enemy.Empowered != null)
            {
                enemy.Empowered.Died(enemy);
                return;
            }

            if (!ByBoss.TryGetValue(enemy.ObjectType, out var info))
                return;
            var remains = new BossRemains(enemy.GameServer, info);
            remains.Move(enemy.X, enemy.Y);
            remains.Z = enemy.Z;
            world.EnterWorld(remains);
        }

        public static bool Holds(Player player)
        {
            var inv = player.Inventory;
            for (var i = 0; i < inv.Length; i++)
                if (inv[i]?.ObjectId == RelicId)
                    return true;
            return false;
        }

        // The remains a relic used by this player would raise: the nearest within its radius that
        // isn't rising already. Null, with the reason, when there are none.
        public static BossRemains RemainsNear(Player player, float radius, out string why)
        {
            why = null;
            if (radius <= 0)
                radius = 3;
            var all = player.World?.StaticObjects.Values.OfType<BossRemains>().ToList() ?? new List<BossRemains>();
            var best = all.Where(r => !r.Rising && r.DistTo(player) <= radius).OrderBy(r => r.DistTo(player)).FirstOrDefault();
            if (best != null)
                return best;
            if (all.Count == 0)
                why = "There are no fallen bosses here for the relic to raise.";
            else if (all.All(r => r.Rising))
                why = "The boss is already rising!";
            else
                why = $"Stand closer to the remains (within {radius:0} tiles) to use the relic.";
            return null;
        }

        public static void Raise(Player player, float radius)
        {
            var remains = RemainsNear(player, radius, out var why);
            if (remains == null)
                player.SendError(why);
            else
                remains.BeginRitual(player);
        }

        /// <summary>The boss's Empowered form, rising at <paramref name="pos"/>.</summary>
        public static Enemy RaiseAt(World world, BossInfo info, Position pos, float z, string raiser)
        {
            if (Entity.Resolve(world.GameServer, info.EmpoweredType) is not Enemy boss)
                return null;
            boss.Empowered = new Empowered(info);
            boss.Move(pos.X, pos.Y);
            boss.Z = z;
            world.EnterWorld(boss);
            boss.Empowered.Risen(boss, raiser);
            return boss;
        }

        /// <summary>The bosses that can be raised whose id or name holds <paramref name="text"/> (/empower).</summary>
        public static List<BossInfo> Find(string text) =>
            ByBoss.Values.Where(b => b.Boss.Contains(text, StringComparison.OrdinalIgnoreCase)
                || b.Name.Contains(text, StringComparison.OrdinalIgnoreCase)).ToList();

        // --- shared bits ---

        public const uint SoulGreen = 0xFF7DFFCF;
        public const uint SoulTeal = 0xFF148C5E;
        public const uint SoulViolet = 0xFF9B5CFF;

        internal static void Effect(Entity at, EffectType type, uint color, Position pos1 = default, Position pos2 = default, int targetId = -1) =>
            at.World?.BroadcastIfVisible(new ShowEffect
            {
                EffectType = type,
                TargetObjectId = targetId == -1 ? at.Id : targetId,
                Pos1 = pos1,
                Pos2 = pos2,
                Color = new ARGB(color)
            }, at);

        internal static void Sound(Entity at, int id) =>
            at.World?.BroadcastIfVisible(new PlaySound { OwnerId = at.Id, SoundId = id }, at);

        internal static void Say(Entity speaker, string name, string text, bool chat)
        {
            speaker.World?.Broadcast(new Text
            {
                Name = "#" + name,
                ObjectId = speaker.Id,
                NumStars = -1,
                BubbleTime = 5,
                Recipient = chat ? "" : "*Bubble*",
                Txt = text,
                NameColor = 0x2FD29A,
                TextColor = 0x7DFFCF
            });
        }

        internal static void Notify(Entity over, string message, uint color) =>
            over.World?.Broadcast(new Notification { ObjectId = over.Id, Message = message, Color = new ARGB(color) });
    }
}
